const NAME_VALIDATION = {
  pattern: "^[a-zA-Z0-9 _-]{1,20}$",
  patternError:
    "Only letters, numbers, spaces, underscores, and dashes allowed (max 20 chars)",
};

const DESCRIPTION_VALIDATION = {
  pattern: "^[a-zA-Z0-9 _-]{1,100}$",
  patternError:
    "Only letters, numbers, spaces, underscores, and dashes allowed (max 100 chars)",
};

function field({
  id,
  label,
  generatedFieldName,
  description,
  format,
  example,
  type = "text",
  required = false,
  systemRequired = false,
  requiredMode,
  placeholder = "",
  defaultValue = "",
  validation,
  options,
  section = "Payment Details",
  generated = true,
  disabledWhen,
  readOnly = false,
}) {
  return {
    id,
    label,
    generatedFieldName,
    description,
    format,
    example,
    type,
    required,
    systemRequired,
    requiredMode,
    placeholder,
    defaultValue,
    validation,
    options,
    section,
    generated,
    disabledWhen,
    readOnly,
  };
}

