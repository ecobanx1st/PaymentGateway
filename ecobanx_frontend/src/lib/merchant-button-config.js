function sectionsFromFields(fields, sectionOrder) {
  return sectionOrder.map((sectionTitle) => ({
    title: sectionTitle,
    fields: fields.filter((item) => item.section === sectionTitle),
  })).filter((section) => section.fields.length > 0);
}

